"""Write-back to CrystFEL .stream format."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from torchsx._core import _SFXStreamCore


def write_stream_reconstruct(
    core: _SFXStreamCore,
    path: str | Path,
    original_stream: str | Path | None = None,
):
    """Generate a valid CrystFEL stream from tensors.

    Parameters
    ----------
    core : _SFXStreamCore
    path : output .stream file path
    original_stream : if provided, copy geometry/unit cell sections verbatim
    """
    path = Path(path)

    # Reverse panel ID mapping
    panel_names: list[str] = []
    if core.geometry:
        panel_names = core.geometry.panel_names
    elif core.metadata and "crystal" in core.metadata:
        panel_names = core.metadata["crystal"].get("panel_names", [])

    # Get filenames and events from metadata
    filenames: list[str] = []
    events: list[str] = []
    if core.metadata and "image" in core.metadata:
        filenames = core.metadata["image"].get("filename", [])
        events = core.metadata["image"].get("event", [])

    # Resolve original_stream: only use if file exists
    if original_stream and not Path(str(original_stream)).exists():
        original_stream = None

    # --- Bulk conversion: tensors → numpy (one-time cost) ---
    # Observations
    hkl_np = core.hkl.cpu().numpy()          # (N_obs, 3)
    I_np = core.I.cpu().numpy()               # (N_obs,)
    sigma_np = core.sigma.cpu().numpy()
    peak_np = core.peak.cpu().numpy()
    bg_np = core.background.cpu().numpy()
    fs_np = core.fs.cpu().numpy()
    ss_np = core.ss.cpu().numpy()
    panel_id_np = core.panel_id.cpu().numpy()
    crystal_id_np = core.crystal_id.cpu().numpy()

    # Crystals
    cell_np = core.cell.cpu().numpy()         # (N_crystals, 6)
    astar_np = core.astar.cpu().numpy() * 10.0  # Å^-1 → nm^-1
    bstar_np = core.bstar.cpu().numpy() * 10.0
    cstar_np = core.cstar.cpu().numpy() * 10.0
    profile_rad_np = core.profile_rad.cpu().numpy() * 10.0  # Å^-1 → nm^-1
    resolution_np = core.resolution.cpu().numpy()
    n_refl_np = core.n_refl.cpu().numpy()
    image_id_np = core.image_id.cpu().numpy()

    # Images
    beam_energy_np = core.beam_energy.cpu().numpy()
    n_peaks_np = core.n_peaks.cpu().numpy()

    # --- Pre-compute observation ranges per crystal using sorted order ---
    # Sort observations by crystal_id for contiguous slicing
    sort_idx = np.argsort(crystal_id_np, kind="stable")
    hkl_np = hkl_np[sort_idx]
    I_np = I_np[sort_idx]
    sigma_np = sigma_np[sort_idx]
    peak_np = peak_np[sort_idx]
    bg_np = bg_np[sort_idx]
    fs_np = fs_np[sort_idx]
    ss_np = ss_np[sort_idx]
    panel_id_np = panel_id_np[sort_idx]

    # Observation offsets per crystal: crystal cid owns obs[offsets[cid]:offsets[cid+1]]
    obs_offsets = np.zeros(core.n_crystals + 1, dtype=np.int64)
    np.cumsum(n_refl_np, out=obs_offsets[1:])

    # --- Pre-compute image → crystal mapping ---
    image_to_crystals: dict[int, list[int]] = {}
    for cid in range(core.n_crystals):
        iid = int(image_id_np[cid])
        image_to_crystals.setdefault(iid, []).append(cid)

    # Panel name lookup array
    max_pid = int(panel_id_np.max()) + 1 if len(panel_id_np) > 0 else 0
    pname_arr = [
        panel_names[i] if i < len(panel_names) else f"m{i}"
        for i in range(max_pid)
    ]

    # Crystallographic constants (parsed from the unit-cell section of the
    # original stream, if present).  Partialator's xsphere model crashes
    # (assertion `kmax > kmin` in do_integral) when these are missing, so we
    # inject them into every reconstructed crystal record.
    lattice_type = None
    centering = None
    unique_axis = None
    if original_stream and Path(str(original_stream)).exists():
        with open(str(original_stream), "r") as orig:
            in_cell = False
            for line in orig:
                if line.startswith("----- Begin unit cell"):
                    in_cell = True
                    continue
                if not in_cell:
                    continue
                if line.startswith("----- End unit cell"):
                    break
                if line.startswith("lattice_type"):
                    lattice_type = line.split("=", 1)[1].strip()
                elif line.startswith("centering"):
                    centering = line.split("=", 1)[1].strip()
                elif line.startswith("unique_axis"):
                    unique_axis = line.split("=", 1)[1].strip()

    det_shift_x_np = core.det_shift_x.cpu().numpy()
    det_shift_y_np = core.det_shift_y.cpu().numpy()

    with open(path, "w") as f:
        # Header
        f.write("CrystFEL stream format 2.3\n")
        f.write("Generated by torchsx\n")

        # Geometry section
        if original_stream:
            _copy_section(f, str(original_stream), "geometry file")
            _copy_section(f, str(original_stream), "unit cell")
        elif core.geometry:
            _write_geometry_section(f, core.geometry)

        # Write chunks
        for iid in range(core.n_images):
            f.write("----- Begin chunk -----\n")

            # Image metadata
            fname = filenames[iid] if iid < len(filenames) else f"image_{iid}"
            event = events[iid] if iid < len(events) else f"//{iid}"
            f.write(f"Image filename: {fname}\n")
            f.write(f"Event: {event}\n")
            f.write(f"Image serial number: {iid}\n")

            f.write(f"hit = 1\n")
            f.write(f"indexed_by = {'xgandalf' if image_to_crystals.get(iid) else 'none'}\n")
            f.write(f"n_indexing_tries = 1\n")
            f.write(f"photon_energy_eV = {beam_energy_np[iid]:.6f}\n")
            # Defaults — partialator's xsphere integrator needs nonzero
            # bandwidth (else kmax == kmin in do_integral and it asserts).
            f.write("beam_divergence = 0.00e+00 rad\n")
            f.write("beam_bandwidth = 1.00e-08 (fraction)\n")
            # average_camera_length in metres
            clen_m = float(core.camera_length[iid].item()) if core.camera_length.numel() > iid else 0.0
            f.write(f"average_camera_length = {clen_m:.6f} m\n")
            f.write(f"num_peaks = {n_peaks_np[iid]}\n")

            crystal_ids = image_to_crystals.get(iid, [])

            # Empty peak list (we don't store raw peaks)
            f.write("Peaks from peak search\n")
            f.write("  fs/px   ss/px (1/d)/nm^-1   Intensity  Panel\n")
            f.write("End of peak list\n")

            # Crystals
            for cid in crystal_ids:
                f.write("--- Begin crystal\n")

                # Cell: Å → nm (÷10)
                a = cell_np[cid, 0] / 10.0
                b = cell_np[cid, 1] / 10.0
                c = cell_np[cid, 2] / 10.0
                al, be, ga = cell_np[cid, 3], cell_np[cid, 4], cell_np[cid, 5]
                f.write(f"Cell parameters {a:.5f} {b:.5f} {c:.5f} nm, "
                        f"{al:.5f} {be:.5f} {ga:.5f} deg\n")

                # Reciprocal vectors (already converted to nm^-1)
                f.write(f"astar = {astar_np[cid,0]:+.7f} {astar_np[cid,1]:+.7f} {astar_np[cid,2]:+.7f} nm^-1\n")
                f.write(f"bstar = {bstar_np[cid,0]:+.7f} {bstar_np[cid,1]:+.7f} {bstar_np[cid,2]:+.7f} nm^-1\n")
                f.write(f"cstar = {cstar_np[cid,0]:+.7f} {cstar_np[cid,1]:+.7f} {cstar_np[cid,2]:+.7f} nm^-1\n")

                if lattice_type is not None:
                    f.write(f"lattice_type = {lattice_type}\n")
                if centering is not None:
                    f.write(f"centering = {centering}\n")
                if unique_axis is not None:
                    f.write(f"unique_axis = {unique_axis}\n")

                f.write(f"profile_radius = {profile_rad_np[cid]:.5f} nm^-1\n")
                # Placeholder refine residuals — partialator xsphere's
                # do_integral crashes without these fields, but the exact
                # values are overwritten during scaling.  Zeros are safe.
                f.write("predict_refine/initial_residual = 0.000000 "
                        "(0.000000 0.000000 0.000000)\n")
                f.write("predict_refine/final_residual = 0.000000 "
                        "(0.000000 0.000000 0.000000)\n")
                f.write("predict_refine/total_shifts = 0.000000e+00 "
                        "0.000000e+00 0.000000e+00\n")
                f.write(
                    f"predict_refine/det_shift x = {det_shift_x_np[iid]:.3f} "
                    f"y = {det_shift_y_np[iid]:.3f} mm\n"
                )

                res_A = float(resolution_np[cid])
                res_nm = 10.0 / res_A if res_A > 0 else 0.0
                f.write(f"diffraction_resolution_limit = {res_nm:.2f} nm^-1 or {res_A:.2f} A\n")

                n_ref = int(n_refl_np[cid])
                f.write(f"num_reflections = {n_ref}\n")
                f.write("num_saturated_reflections = 0\n")
                f.write("num_implausible_reflections = 0\n")

                # Reflections — contiguous slice, no per-element tensor access
                f.write("Reflections measured after indexing\n")
                f.write("   h    k    l          I   sigma(I)       peak background  fs/px  ss/px panel\n")

                lo = obs_offsets[cid]
                hi = obs_offsets[cid + 1]

                # Build all reflection lines at once
                lines = []
                for j in range(lo, hi):
                    lines.append(
                        f"{hkl_np[j,0]:4d} {hkl_np[j,1]:4d} {hkl_np[j,2]:4d} "
                        f"{I_np[j]:10.2f} {sigma_np[j]:10.2f} {peak_np[j]:10.2f} {bg_np[j]:10.2f}"
                        f"{fs_np[j]:7.1f} {ss_np[j]:>6.1f} {pname_arr[panel_id_np[j]]}\n"
                    )
                f.write("".join(lines))

                f.write("End of reflections\n")
                f.write("--- End crystal\n")

            f.write("----- End chunk -----\n")


def write_stream_patch(
    core: _SFXStreamCore,
    original_path: str | Path,
    output_path: str | Path,
):
    """Patch an existing stream with updated I/sigma values.

    Only works if crystal count hasn't changed (no filtering applied).
    Preserves all text, comments, headers intact.
    """
    original_path = Path(original_path)
    output_path = Path(output_path)

    # Bulk convert to numpy once
    I_np = core.I.cpu().numpy()
    sigma_np = core.sigma.cpu().numpy()
    n_refl_np = core.n_refl.cpu().numpy()
    n_obs = core.n_observations

    crystal_idx = 0
    obs_offset = 0

    with open(original_path, "r") as fin, open(output_path, "w") as fout:
        in_reflections = False
        refl_line_idx = 0
        current_n_refl = 0

        for line in fin:
            if line.startswith("Reflections measured after indexing"):
                in_reflections = True
                refl_line_idx = 0
                if crystal_idx < core.n_crystals:
                    current_n_refl = int(n_refl_np[crystal_idx])
                fout.write(line)
                continue

            if in_reflections:
                if line.strip().startswith("h") or line.strip().startswith("---"):
                    fout.write(line)
                    continue

                if line.startswith("End of reflections"):
                    in_reflections = False
                    obs_offset += current_n_refl
                    crystal_idx += 1
                    fout.write(line)
                    continue

                # Replace I and sigma in this reflection line
                parts = line.split()
                oi = obs_offset + refl_line_idx
                if len(parts) >= 10 and oi < n_obs:
                    I_val = I_np[oi]
                    sig = sigma_np[oi]
                    h, k, l = int(parts[0]), int(parts[1]), int(parts[2])
                    pk = float(parts[5])
                    bg = float(parts[6])
                    fs_val = float(parts[7])
                    ss_val = float(parts[8])
                    pname = parts[9]
                    fout.write(
                        f"{h:4d} {k:4d} {l:4d} "
                        f"{I_val:10.2f} {sig:10.2f} {pk:10.2f} {bg:10.2f}"
                        f"{fs_val:7.1f} {ss_val:>6.1f} {pname}\n"
                    )
                    refl_line_idx += 1
                else:
                    fout.write(line)
                    refl_line_idx += 1
                continue

            fout.write(line)


def _copy_section(fout, stream_path: str, section_name: str):
    """Copy a named section from a stream file."""
    begin_marker = f"----- Begin {section_name} -----"
    end_marker = f"----- End {section_name} -----"
    with open(stream_path, "r") as fin:
        in_section = False
        for line in fin:
            if line.startswith(begin_marker):
                in_section = True
                fout.write(line)
            elif line.startswith(end_marker):
                fout.write(line)
                return
            elif in_section:
                fout.write(line)


def _write_geometry_section(fout, geometry):
    """Write geometry as a .stream geometry section."""
    fout.write("----- Begin geometry file -----\n")
    fout.write(f"photon_energy = {geometry.photon_energy_eV} eV\n")
    fout.write(f"clen = {geometry.clen}\n")
    fout.write(f"res = {geometry.res}\n")
    if geometry.data_path:
        fout.write(f"data = {geometry.data_path}\n")
    if geometry.mask_file:
        fout.write(f"mask0_file = {geometry.mask_file}\n")
    if geometry.mask_data:
        fout.write(f"mask0_data = {geometry.mask_data}\n")
    fout.write(f"adu_per_eV = {geometry.adu_per_eV}\n")
    fout.write("\n")

    for p in geometry.panels:
        fout.write(f"{p.name}/min_fs = {p.min_fs}\n")
        fout.write(f"{p.name}/max_fs = {p.max_fs}\n")
        fout.write(f"{p.name}/min_ss = {p.min_ss}\n")
        fout.write(f"{p.name}/max_ss = {p.max_ss}\n")
        fout.write(f"{p.name}/corner_x = {p.corner_x}\n")
        fout.write(f"{p.name}/corner_y = {p.corner_y}\n")
        fs = p.fs_vec
        ss = p.ss_vec
        fout.write(f"{p.name}/fs = {fs[0]}x {fs[1]}y {fs[2]}z\n")
        fout.write(f"{p.name}/ss = {ss[0]}x {ss[1]}y {ss[2]}z\n")
        fout.write(f"{p.name}/coffset = {p.coffset}\n")
        fout.write("\n")

    fout.write("----- End geometry file -----\n")
