"""CrystFEL header interpretation; reflection parsing stays in _parse."""
from __future__ import annotations

from pathlib import Path
import math
import re
import shlex

from torchsx.measurement import MeasurementSpec, parse_radii


def read_measurement(path) -> MeasurementSpec:
    """Read the pre-chunk header once. Recorded commands are data, never run."""
    version = method = radii = None
    modifiers = ()
    declarations, provenance, unresolved = [], [], []
    in_geometry = False
    with open(path, encoding="utf-8", errors="replace") as f:
        for raw in f:
            line = raw.strip()
            if line == "----- Begin chunk -----":
                break
            if line == "----- Begin geometry file -----":
                in_geometry = True
                continue
            if line == "----- End geometry file -----":
                in_geometry = False
                continue
            if in_geometry:
                key, sep, value = line.split(";", 1)[0].partition("=")
                key = key.strip()
                if sep and key.rsplit("/", 1)[-1] in ("adu_per_photon", "adu_per_eV"):
                    scope, _, convention = key.rpartition("/")
                    try:
                        number = float(value.split()[0])
                        if not math.isfinite(number):
                            number = None
                    except (ValueError, IndexError):
                        number = None
                    declarations.append((scope or "global", convention, number))
                    if number is None or number <= 0:
                        unresolved.append("gain")
                    provenance.append((f"gain:{key}", line))
                continue
            match = re.match(r"Generated by CrystFEL\s+(\S+)", line)
            if match:
                version = match[1]
            if "indexamajig" not in line:
                continue
            try:
                words = shlex.split(line)
            except ValueError:
                unresolved.append("producer_command")
                continue
            if not words or Path(words[0]).name != "indexamajig":
                continue
            provenance.append(("producer_command", line))
            options = {}
            for i, word in enumerate(words):
                key, sep, value = word.partition("=")
                if key in ("--int-radius", "--integration"):
                    options[key] = value if sep else (words[i + 1] if i + 1 < len(words) else "")
            if "--int-radius" in options:
                try:
                    radii = parse_radii(options["--int-radius"])
                except ValueError as exc:
                    raise ValueError(f"Invalid CrystFEL --int-radius {options['--int-radius']!r}: {exc}") from exc
            if "--integration" in options:
                if not options["--integration"] or options["--integration"].startswith("--"):
                    raise ValueError(f"Invalid CrystFEL --integration {options['--integration']!r}: expected an integration method")
                method, *mods = re.split("[-,]", options["--integration"])
                modifiers = tuple(mods)
                # Unknown modifiers stay visible and require an explicit recipe.
                if any(m not in ("cen", "nocen", "sat", "nosat", "grad", "nograd", "rescut", "norescut") for m in mods):
                    unresolved.append("integration_modifiers")
    if method is None:
        # indexamajig defaults (im-argparse.c); omission is a normal recipe,
        # not missing information requiring a user override.
        method, modifiers = "rings", ("nocen", "nosat", "nograd")
        provenance.append(("default:integration", "CrystFEL rings-nocen-nosat-nograd"))
    if radii is None:
        # indexamajig.c supplies these when --int-radius is omitted.
        radii = (4.0, 5.0, 7.0)
        provenance.append(("default:radii", "CrystFEL 4,5,7"))
    if not declarations:
        unresolved.append("gain")
    n_peak = n_bg = None
    if radii is not None:
        from torchsx.merging.hkl.noise import _crystfel_pixel_counts
        n_peak, n_bg = _crystfel_pixel_counts(*radii)
    return MeasurementSpec(
        producer="crystfel", producer_version=version,
        integration_method=method, integration_modifiers=modifiers,
        intensity_unit="adu", intensity_definition="background_subtracted_sum",
        background_unit="adu/pixel",
        background_definition=("local_plane_at_peak" if next((m for m in reversed(modifiers)
                               if m in ("grad", "nograd")), None) == "grad"
                               else "local_mean_per_pixel"),
        uncertainty_definition="supplied_sigma_of_intensity",
        gain_declarations=tuple(declarations), radii=radii,
        nominal_n_peak=n_peak, nominal_n_bg=n_bg,
        pixel_count_definition="nominal_integer_ring_mask" if radii else "unknown",
        source_files=(str(Path(path).resolve()),), provenance=tuple(provenance),
        unresolved=tuple(dict.fromkeys(unresolved)),
    )
