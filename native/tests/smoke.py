"""Smoke test for an installed torchsx-native wheel; needs only numpy.

Run against every wheel CI builds, on its own platform. It indexes, parses and
writes a small stream with one malformed reflection line, then re-parses the
written file. The full parity tests against the Python parser live in
``tests/test_native_parse.py`` and need torchsx itself.
"""
import sys
import tempfile
from pathlib import Path

import numpy as np
import torchsx_native as n

REFL = "{h:4d} {k:4d} {l:4d} {i:10.2f} {s:10.2f} {p:10.2f} {b:10.2f}{fs:7.1f} {ss:6.1f} {panel}\n"


def chunk(i: int) -> str:
    rows = "".join(
        REFL.format(h=i, k=j, l=-j, i=10.0 * j, s=1.5, p=5.0, b=0.25, fs=100.0 + j, ss=200.0, panel="p1" if j % 2 else "p0")
        for j in range(4)
    )
    return (
        "----- Begin chunk -----\n"
        f"Image filename: /raw/img{i}.h5\nEvent: //{i}\n"
        "photon_energy_eV = 12960.000000\naverage_camera_length = 0.093900 m\nnum_peaks = 7\n"
        "Peaks from peak search\nEnd of peak list\n"
        "--- Begin crystal\n"
        "Cell parameters 7.94000 7.94000 3.81000 nm, 90.00000 90.00000 90.00000 deg\n"
        "astar = +0.1259446 +0.0000000 +0.0000000 nm^-1\n"
        "bstar = +0.0000000 +0.1259446 +0.0000000 nm^-1\n"
        "cstar = +0.0000000 +0.0000000 +0.2624672 nm^-1\n"
        "profile_radius = 0.00100 nm^-1\n"
        "predict_refine/det_shift x = 0.010 y = -0.020 mm\n"
        "diffraction_resolution_limit = 5.00 nm^-1 or 2.00 A\n"
        "Reflections measured after indexing\n"
        "   h    k    l          I   sigma(I)       peak background  fs/px  ss/px panel\n"
        f"{rows}"
        + ("   1    2    3 not-a-number\n" if i == 1 else "")
        + "End of reflections\n--- End crystal\n----- End chunk -----\n"
    )


def main() -> None:
    assert isinstance(n.PROTOCOL, int) and n.__version__, (n.PROTOCOL, n.__version__)
    header = "CrystFEL stream format 2.3\nGenerated by smoke\n"
    with tempfile.TemporaryDirectory() as d:
        src = Path(d) / "in.stream"
        src.write_bytes((header + "".join(chunk(i) for i in range(5))).encode())

        rows = n.index_chunks(str(src), 1)
        assert rows.shape == (5, 4) and rows.dtype == np.int64, rows
        assert np.array_equal(rows, n.index_chunks(str(src), 3))
        assert rows[:, 3].tolist() == [4, 4, 4, 4, 4], rows  # the bad line has < 10 fields

        cols, filenames, events, report = n.parse_chunks(str(src), rows, ["p0", "p1"], 2)
        assert dict(report) == {"reflection_short": (1, dict(report)["reflection_short"][1])}, report
        assert cols["I"].shape == (20,) and cols["hkl"].shape == (20, 3) and cols["cell"].shape == (5, 6)
        assert filenames == [f"/raw/img{i}.h5" for i in range(5)] and events == [f"//{i}" for i in range(5)]
        assert cols["panel_id"].tolist() == [0, 1, 0, 1] * 5
        assert np.isclose(cols["cell"][0, 0], 79.4) and cols["resolution"][0] == np.float32(2.0)

        arrays = {k: v for k, v in cols.items() if k not in ("crystal_id", "crystal_in_image")}
        out = Path(d) / "out.stream"
        n.write_stream(str(out), arrays, filenames, events, ["p0", "p1"], None, None, None, header, 2)
        again, fn2, ev2, rep2 = n.parse_chunks(str(out), n.index_chunks(str(out), 2), ["p0", "p1"], 2)
        assert dict(rep2) == {} and (fn2, ev2) == (filenames, events)
        for k in ("hkl", "I", "sigma", "fs", "ss", "panel_id", "crystal_id", "n_refl", "image_id", "n_peaks"):
            assert np.array_equal(again[k], cols[k]), k
    print(f"torchsx_native {n.__version__} (protocol {n.PROTOCOL}) OK on Python {sys.version.split()[0]}")


if __name__ == "__main__":
    main()
