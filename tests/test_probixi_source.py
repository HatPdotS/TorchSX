"""Probixi as a datasource: its recipe header, extra reflection columns and model background.

Probixi writes a CrystFEL 2.3 stream whose header declares the run's own
integration recipe (``probixi/int_radius``, ``probixi/adu_per_photon``, ...)
and whose reflection rows carry three trailing columns: the disk pixels
actually summed, the noise-model background under those pixels and that
estimate's variance. These tests pin the adapter that reads all of it and the
``--background model`` preparation that turns it into a per-observation
detection background with its own variance.
"""
from __future__ import annotations

import math

import pytest
import torch

from torchsx.io import _native
from torchsx.io._crystfel import read_measurement
from torchsx.io._metadata import StreamMetadata
from torchsx.io._probixi import PROBIXI_COLUMNS, read_reflection_columns
from torchsx.measurement import gain_from_measurement, resolve_measurement
from torchsx.merging.config import MergeConfig
from torchsx.merging.hkl.noise import PoissonNoiseModel, _crystfel_pixel_counts
from torchsx.merging.observations import prepare_observations
from torchsx.stream import SFXStream

RECIPE = ("probixi/int_radius = 1.50,6.00,8.60\n"
          "probixi/adu_per_photon = 9.9\n"
          "probixi/bg_annulus_pixels = 280\n"
          "probixi/aperture = snr\n"
          "probixi/reflection_columns = n_pix bg_model bg_model_var\n")


def _extras(i: int) -> tuple[int, float, float]:
    # deterministic per-row values a test can recompute from the row index
    return 9 - i % 3, 20.0 + 2.5 * i, 0.5 + 0.1 * i


def _probixi_stream(tmp_path, sample_core, *, recipe: str = RECIPE, extras: bool = True):
    """A stream in probixi's dialect, from the shared synthetic core."""
    from torchsx.io._writeback import _write_stream_reconstruct_python
    path = tmp_path / "probixi.stream"
    metadata = StreamMetadata(image={"filename": ["/raw/a.h5", "/raw/b.h5"],
                                     "event": ["//5", "//8"]})
    core = sample_core.replace(metadata=metadata, friedel_merged=False)
    _write_stream_reconstruct_python(core, path)
    text = path.read_text().replace("Generated by torchsx\n", "Generated by probixi\n" + recipe)
    text = text.replace("adu_per_eV = 1.0", "adu_per_photon = 1.0")
    if extras:
        out, i, in_table = [], 0, False
        for line in text.splitlines():
            if line.startswith("Reflections measured after indexing"):
                in_table = True
            elif line.startswith("End of reflections"):
                in_table = False
            elif in_table and line.startswith("   h    k    l"):
                line += "  n_pix   bg_model bg_model_var"
            elif in_table:
                n_pix, bg_model, var = _extras(i)
                line += f" {n_pix:5d} {bg_model:10.2f} {var:12.5g}"
                i += 1
            out.append(line)
        text = "\n".join(out) + "\n"
    path.write_text(text)
    return path


@pytest.fixture
def python_parser(monkeypatch):
    monkeypatch.setattr(_native, "load", lambda: None)


# ── the header ────────────────────────────────────────────────────────

def test_probixi_header_declares_the_run_recipe(tmp_path, sample_core):
    spec = read_measurement(_probixi_stream(tmp_path, sample_core))
    assert spec.producer == "probixi"
    assert spec.integration_method == "rings"
    assert spec.radii == (1.5, 6.0, 8.6)
    assert (spec.nominal_n_peak, spec.nominal_n_bg) == _crystfel_pixel_counts(1.5, 6.0, 8.6)
    assert spec.reflection_columns == PROBIXI_COLUMNS
    # the run's measured gain, not the geometry file's nominal 1.0
    assert spec.gain_declarations == (("probixi", "adu_per_photon", 9.9),)
    assert gain_from_measurement(spec, 12960.0) == pytest.approx(9.9)
    assert "gain" not in spec.unresolved and "radii" not in spec.unresolved
    resolved = resolve_measurement(spec)
    assert resolved.radii == (1.5, 6.0, 8.6)
    assert dict(resolved.provenance) == {"radii": "source", "gain": "source"}
    assert any(key == "probixi:probixi/int_radius" for key, _ in spec.provenance)


def test_probixi_header_without_recipe_stays_unresolved(tmp_path, sample_core):
    """No CrystFEL defaults for probixi: a header without radii needs --int-radius."""
    spec = read_measurement(_probixi_stream(tmp_path, sample_core, recipe="", extras=False))
    assert spec.producer == "probixi"
    assert spec.radii is None and "radii" in spec.unresolved
    assert spec.reflection_columns == ()
    # the geometry's declaration is all there is for the gain
    assert spec.gain_declarations == (("global", "adu_per_photon", 1.0),)
    with pytest.raises(ValueError, match="--int-radius"):
        resolve_measurement(spec)
    resolved = resolve_measurement(spec, radii="1.5,6,8.6")
    assert dict(resolved.provenance)["radii"] == "explicit"


def test_crystfel_header_is_unchanged(tmp_path):
    path = tmp_path / "c.stream"
    path.write_text("CrystFEL stream format 2.3\nGenerated by CrystFEL 0.13.0\n"
                    "indexamajig --int-radius=3,4,7\n----- Begin geometry file -----\n"
                    "adu_per_photon = 1.0\n----- End geometry file -----\n----- Begin chunk -----\n")
    spec = read_measurement(path)
    assert spec.producer == "crystfel" and spec.reflection_columns == ()
    assert spec.radii == (3.0, 4.0, 7.0)


# ── the columns ───────────────────────────────────────────────────────

def _check_columns(stream, n):
    for name in PROBIXI_COLUMNS:
        assert name in stream._core.levels["obs"]
    expected = torch.tensor([_extras(i) for i in range(n)])
    assert torch.equal(stream._core.n_pix, expected[:, 0])
    assert torch.allclose(stream._core.bg_model, expected[:, 1])
    assert torch.allclose(stream._core.bg_model_var, expected[:, 2])


def test_extra_columns_become_observation_columns(tmp_path, sample_core, python_parser):
    path = _probixi_stream(tmp_path, sample_core)
    stream = SFXStream.read(path, spacegroup="P 1", merge_friedel=False)
    assert stream.n_observations == sample_core.n_observations
    _check_columns(stream, stream.n_observations)
    # the standard ten columns are the same the CrystFEL reader would give
    assert torch.allclose(stream.I, sample_core.I)
    assert torch.allclose(stream._core.background, sample_core.background)


@pytest.mark.skipif(_native.load() is None, reason="native parser not built")
def test_extra_columns_with_the_native_parser(tmp_path, sample_core):
    stream = SFXStream.read(_probixi_stream(tmp_path, sample_core), spacegroup="P 1",
                            merge_friedel=False)
    _check_columns(stream, stream.n_observations)


def test_extra_columns_survive_cache_and_filtering(tmp_path, sample_core, python_parser):
    path = _probixi_stream(tmp_path, sample_core)
    stream = SFXStream.read(path, spacegroup="P 1", merge_friedel=False)
    stream.save(tmp_path / "cache.sfx")
    again = SFXStream.load(tmp_path / "cache.sfx", merge_friedel=False)
    _check_columns(again, again.n_observations)
    assert again.measurement.reflection_columns == PROBIXI_COLUMNS
    # a row subset keeps every extra aligned with its observation
    keep = torch.tensor([True, False, True, True, False])
    sub = stream._core.select_cascade({"obs": keep})
    assert torch.equal(sub.n_pix, stream._core.n_pix[keep])
    assert torch.equal(sub.bg_model_var, stream._core.bg_model_var[keep])


def test_rows_without_extras_read_as_nan(tmp_path, sample_core, python_parser):
    """A crystal written without prediction has the ten columns only."""
    path = _probixi_stream(tmp_path, sample_core)
    lines = path.read_text().splitlines()
    # strip the extras from the very first reflection row
    first = next(i for i, line in enumerate(lines)
                 if lines[i - 1].startswith("   h    k    l"))
    lines[first] = " ".join(lines[first].split()[:10])
    path.write_text("\n".join(lines) + "\n")
    stream = SFXStream.read(path, spacegroup="P 1", merge_friedel=False)
    assert torch.isnan(stream._core.bg_model[0]) and not torch.isnan(stream._core.bg_model[1:]).any()


def test_row_count_mismatch_is_refused(tmp_path, sample_core):
    path = _probixi_stream(tmp_path, sample_core)
    with pytest.raises(ValueError, match="reflection rows"):
        read_reflection_columns(path, PROBIXI_COLUMNS, n_obs=sample_core.n_observations + 1)


def test_sampled_parse_warns_and_drops_the_columns(tmp_path, sample_core, python_parser):
    path = _probixi_stream(tmp_path, sample_core)
    with pytest.warns(UserWarning, match="extra reflection columns"):
        stream = SFXStream.from_stream(path, spacegroup="P 1", max_crystals=1, sequential=True)
    assert "bg_model" not in stream._core.levels["obs"]


# ── the model background ──────────────────────────────────────────────

def _prepare(stream, background):
    noise = PoissonNoiseModel(r_peak=1.5, r_gap=6.0, r_bg=8.6, gain=9.9)
    return prepare_observations(stream, MergeConfig(gain=9.9), poisson_noise=noise,
                                background=background), noise


def test_model_background_is_the_producers_estimate(tmp_path, sample_core, python_parser):
    stream = SFXStream.read(_probixi_stream(tmp_path, sample_core), spacegroup="P 1",
                            merge_friedel=False)
    core = stream._core
    gain = 9.9
    prep, noise = _prepare(stream, "model")
    n = core.n_observations
    extras = torch.tensor([_extras(i) for i in range(n)])
    # the disk's raw count from the exact pixel count, in photons
    raw = (core.I + core.background * extras[:, 0]) / gain
    bg_model = extras[:, 1] / gain
    var = extras[:, 2] / gain ** 2
    # the preparation reorders by reflection, so compare as multisets of rows
    got = torch.stack([prep.I_obs + prep.bg, prep.bg, prep.bg_var], 1)
    want = torch.stack([raw, bg_model, var], 1)
    got = got[torch.argsort(got[:, 1])]
    want = want[torch.argsort(want[:, 1])]
    assert torch.allclose(got, want, atol=1e-5)
    # sigma is NOT recomputed: the stream's sigma (in photons) weights the EMA merge
    # target, and a counts-based sigma biases that average low
    sig = prep.obs_info.sigma[torch.argsort(prep.bg)]
    assert torch.allclose(sig, (core.sigma / gain)[torch.argsort(bg_model)], atol=1e-5)

    annulus, _ = _prepare(stream, "annulus")
    assert annulus.bg_var is None
    assert torch.allclose(annulus.bg.sort().values,
                          (core.background * noise.n_peak / gain).sort().values)
    assert torch.allclose(annulus.I_obs.sort().values, (core.I / gain).sort().values)


def test_model_background_needs_the_columns(sample_core):
    with pytest.raises(ValueError, match="n_pix"):
        prepare_observations(SFXStream(sample_core), MergeConfig(gain=1.0), background="model")
    with pytest.raises(ValueError, match="background must be"):
        prepare_observations(SFXStream(sample_core), MergeConfig(gain=1.0), background="ring")


def test_model_background_rejects_rows_without_an_estimate(tmp_path, sample_core, python_parser, capsys):
    path = _probixi_stream(tmp_path, sample_core)
    lines = path.read_text().splitlines()
    first = next(i for i, line in enumerate(lines)
                 if lines[i - 1].startswith("   h    k    l"))
    lines[first] = " ".join(lines[first].split()[:10])
    path.write_text("\n".join(lines) + "\n")
    stream = SFXStream.read(path, spacegroup="P 1", merge_friedel=False)
    prep, _ = _prepare(stream, "model")
    assert prep.I_obs.numel() == sample_core.n_observations - 1
    assert "bg_model=1" in capsys.readouterr().out
    # the annulus mode still uses every row
    annulus, _ = _prepare(stream, "annulus")
    assert annulus.I_obs.numel() == sample_core.n_observations
