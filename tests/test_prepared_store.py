def _synthetic_core(geometry, *, n_images=40, seed=0, sigma_bad=True):
    """Frames of one or two crystals, 5-60 reflections each, a few invalid values."""
    g = torch.Generator().manual_seed(seed)
    cols = {k: [] for k in ("hkl", "I", "sigma", "background", "peak", "fs", "ss",
                            "panel_id", "crystal_id")}
    crys = {k: [] for k in ("astar", "bstar", "cstar", "cell", "profile_rad", "resolution",
                            "n_refl", "image_id", "crystal_in_image")}
    n_crys = 0
    for img in range(n_images):
        for lattice in range(1 + int(torch.rand(1, generator=g) < 0.3)):
            n = int(torch.randint(5, 60, (1,), generator=g))
            cols["hkl"].append(torch.randint(-7, 8, (n, 3), generator=g).to(torch.int16))
            cols["I"].append(torch.randn(n, generator=g) * 40 + 15)
            cols["sigma"].append(torch.rand(n, generator=g) * 5 + 0.5)
            cols["background"].append(torch.rand(n, generator=g) * 3)
            cols["peak"].append(torch.rand(n, generator=g) * 100)
            cols["fs"].append(torch.rand(n, generator=g) * 1000)
            cols["ss"].append(torch.rand(n, generator=g) * 1000)
            cols["panel_id"].append(torch.randint(0, 2, (n,), generator=g).to(torch.int16))
            cols["crystal_id"].append(torch.full((n,), n_crys, dtype=torch.int32))
            a, b, c = (torch.tensor([15.0, 19.0, 21.0]) * (1 + 0.01 * torch.randn(3, generator=g))).tolist()
            rot = torch.linalg.qr(torch.eye(3) + 0.05 * torch.randn(3, 3, generator=g))[0]
            crys["astar"].append(rot[0] / a)
            crys["bstar"].append(rot[1] / b)
            crys["cstar"].append(rot[2] / c)
            crys["cell"].append(torch.tensor([a, b, c, 90.0, 90.0, 90.0]))
            crys["profile_rad"].append(torch.tensor(0.004))
            crys["resolution"].append(torch.rand(1, generator=g)[0] * 2 + 1.5)
            crys["n_refl"].append(torch.tensor(n, dtype=torch.int32))
            crys["image_id"].append(torch.tensor(img, dtype=torch.int32))
            crys["crystal_in_image"].append(torch.tensor(lattice, dtype=torch.int32))
            n_crys += 1
    obs = {k: torch.cat(v) for k, v in cols.items()}
    for k in ("I", "sigma", "background", "peak", "fs", "ss"):
        obs[k] = obs[k].float()
    if sigma_bad:
        obs["I"][7] = float("nan")
        obs["sigma"][11] = 0.0
        obs["background"][13] = float("inf")
    crys = {k: torch.stack(v).float() if k not in ("n_refl", "image_id", "crystal_in_image")
            else torch.stack(v) for k, v in crys.items()}
    meta = StreamMetadata(image={"filename": [f"/raw/run{i // 10}.h5" for i in range(n_images)],
                                 "event": [f"//{i}" for i in range(n_images)]})
    return _SFXStreamCore(
        **obs, **crys,
        beam_energy=12960.0 + torch.randn(n_images, generator=g) * 5,
        det_shift_x=torch.randn(n_images, generator=g) * 0.01,
        det_shift_y=torch.randn(n_images, generator=g) * 0.01,
        n_peaks=torch.randint(5, 50, (n_images,), generator=g).to(torch.int32),
        geometry=geometry, metadata=meta, spacegroup="P 1", source_path="synthetic.stream",
    )


def _write(core, path):
    from torchsx.io._writeback import _write_stream_reconstruct_python
    _write_stream_reconstruct_python(core.replace(friedel_merged=False), path)
    text = path.read_text().replace("Generated by torchsx", "Generated by CrystFEL 0.13.0\n"
                                    "indexamajig --integration=rings-cen --int-radius=3,4,7")
    path.write_text(text.replace("adu_per_eV = 1.0", "adu_per_photon = 1.0"))
    return path


