def _reference(paths, *, spacegroup, merge_friedel, d_min, gain, extra=None):
    """The in-memory preparation: read, cut, concatenate, prepare."""
    parts = []
    for path in paths:
        s = SFXStream.read(path, spacegroup=spacegroup, merge_friedel=merge_friedel)
        parts.append(SFXStream(filter_resolution(s._core, d_min=d_min, d_max=999.0)))
    stream = parts[0] if len(parts) == 1 else SFXStream.concat(parts)
    if extra:
        stream = SFXStream.concat([stream] + [stream.filter_crystals(m) for m in extra])
    noise = PoissonNoiseModel(r_peak=3, r_gap=4, r_bg=7, gain=1.0)
    return prepare_observations(stream, MergeConfig(gain=gain), poisson_noise=noise), noise


def _build(paths, out, *, spacegroup, merge_friedel, d_min, gain, extra=None, block_obs=37):
    b = PS.StoreBuilder(out.with_name("raw"), spacegroup=spacegroup, merge_friedel=merge_friedel,
                        block_obs=block_obs)
    for i, path in enumerate(paths):
        b.add(str(i), path)
    b.filter_resolution(d_min)
    b.set_layout(extra)
    noise = PoissonNoiseModel(r_peak=3, r_gap=4, r_bg=7, gain=1.0)
    return b.finish(out, config=MergeConfig(gain=gain), noise=noise), noise


def _crystal_major(prep):
    """Rows ordered by (crystal, reflection, intensity) -- an order both layouts share."""
    oi = prep.obs_info
    key = np.lexsort((prep.I_obs.numpy(), oi.hkl_idx.numpy(), oi.crystal_id.numpy()))
    return torch.from_numpy(key)


def _assert_same(ref, store):
    mat = store.materialize()
    for name in ("hkl_valid", "d_spacing", "median_cell", "obs_counts", "shell_id_fw",
                 "is_centric"):
        assert torch.equal(getattr(ref, name).cpu(), getattr(mat, name).cpu()), name
    assert (ref.n_valid, ref.n_obs_total) == (mat.n_valid, mat.n_obs_total)
    assert ref.obs_info.n_crystals == mat.obs_info.n_crystals
    assert torch.equal(ref.obs_info.crystal_feat, mat.obs_info.crystal_feat)
    # crystal-major, each crystal's rows sorted by reflection
    oi = mat.obs_info
    assert bool((oi.crystal_id[1:] >= oi.crystal_id[:-1]).all())
    same_crystal = oi.crystal_id[1:] == oi.crystal_id[:-1]
    assert bool((oi.hkl_idx[1:][same_crystal] >= oi.hkl_idx[:-1][same_crystal]).all())
    a, b = _crystal_major(ref), _crystal_major(mat)
    assert torch.equal(ref.I_obs[a], mat.I_obs[b])
    assert torch.equal(ref.bg[a], mat.bg[b])
    for name in OBS_FIELDS:
        left, right = getattr(ref.obs_info, name), getattr(oi, name)
        assert (left is None) == (right is None), name
        if left is not None:
            assert torch.equal(left[a], right[b]), name
    # The sums written block by block are those of one pass over the store's rows ...
    assert torch.equal(store.unity_merge(),
                       unity_merge(mat.I_obs, oi.sigma, mat.hkl_id, mat.n_valid))
    assert torch.equal(store.plain_mean(), plain_mean(mat.I_obs, mat.hkl_id, mat.n_valid))
    # ... and agree with the reference up to the order of summation (an unstable
    # sort orders the reference's equal keys arbitrarily at this size).
    ref_unity = unity_merge(ref.I_obs, ref.obs_info.sigma, ref.hkl_id, ref.n_valid)
    d = (ref_unity - store.unity_merge()).abs()
    assert float(d.max()) < 1e-3 + 1e-4 * float(ref_unity.abs().max()), float(d.max())
    assert torch.allclose(plain_mean(ref.I_obs, ref.hkl_id, ref.n_valid), store.plain_mean(),
                          rtol=1e-5, atol=1e-5)


@pytest.mark.parametrize("merge_friedel", [True, False])
def test_store_matches_in_memory_preparation(streams, tmp_path, parser, merge_friedel):
    kw = dict(spacegroup="P 2 2 2", merge_friedel=merge_friedel, d_min=2.2, gain=2.5)
    ref, ref_noise = _reference(streams, **kw)
    store, noise = _build(streams, tmp_path / "store", **kw)
    _assert_same(ref, store)
    assert noise.gain == ref_noise.gain == 2.5


def test_store_duplicates_crystals_like_concatenated_copies(streams, tmp_path, parser):
    kw = dict(spacegroup="P 1", merge_friedel=True, d_min=2.0, gain=1.0)
    s = SFXStream(filter_resolution(SFXStream.read(streams[0], spacegroup="P 1")._core, 2.0, 999.0))
    g = torch.Generator().manual_seed(3)
    extra = [torch.rand(s.n_crystals, generator=g) < 0.4 for _ in range(2)]
    ref, _ = _reference(streams[:1], extra=extra, **kw)
    store, _ = _build(streams[:1], tmp_path / "store", extra=extra, **kw)
    _assert_same(ref, store)


def test_calibrated_gain_matches(streams, tmp_path, parser, monkeypatch):
    """The calibration sees the same observations, so it selects the same gain."""
    seen = []

    def truncnorm(self, I, bg, **kw):
        neg = (I < 0) & (bg > 0.1)
        seen.append((I[neg].clone(), bg[neg].clone()))
        self.gain_calibration_info = {"method": "fixture", "valid": True}
        return 3.0, 0.0
    monkeypatch.setattr(PoissonNoiseModel, "calibrate_gain_truncnorm", truncnorm)
    kw = dict(spacegroup="P 1", merge_friedel=True, d_min=2.0, gain="calibrate")
    ref, ref_noise = _reference(streams, **kw)
    store, noise = _build(streams, tmp_path / "store", **kw)
    assert noise.gain == ref_noise.gain == 3.0
    assert torch.equal(seen[0][0], seen[1][0]) and torch.equal(seen[0][1], seen[1][1])
    _assert_same(ref, store)


def test_reader_returns_the_requested_rows(streams, tmp_path, parser):
    store, _ = _build(streams, tmp_path / "store", spacegroup="P 1", merge_friedel=True,
                      d_min=2.0, gain=1.0)
    raw = np.fromfile(tmp_path / "store" / "obs.bin", dtype=RECORD)
    reader = ObservationStore(tmp_path / "store", len(raw))
    g = torch.Generator().manual_seed(0)
    for rows in (torch.randperm(len(raw), generator=g)[:50],
                 torch.arange(10, 90), torch.tensor([3, 4, 5, 9, 2, 2, 7])):
        reader.prefetch(rows)
        got = reader.read(rows.clone()).numpy().view(RECORD).reshape(-1)
        assert np.array_equal(got, raw[rows.numpy()])
    assert reader.read(rows) is reader.read(rows.clone())     # the last batch is kept
    idx = torch.randint(len(raw), (500,), generator=g)
    oi = store.gather(idx)
    assert torch.equal(oi.obs_id, idx)
    assert torch.equal(oi.I_obs, torch.from_numpy(raw["I_obs"][idx.numpy()]))
    for chunk in (7, 1 << 20):
        rows = np.concatenate([rec for _, rec in reader.scan(chunk)])
        assert np.array_equal(rows, raw)


def _train_and_merge(prep, tmp_path):
    from tests.test_cli_pipeline import _stack
    torch.manual_seed(5)
    scale, obj, tr = _stack(prep, None, tmp_path)
    for _, rows in tr.index.batches(3000, generator=torch.Generator().manual_seed(1)):
        tr.step(rows)
    scale.eval()
    return tr.merge()


def test_trainer_on_store_matches_in_memory(streams, tmp_path, parser):
    store, _ = _build(streams, tmp_path / "store", spacegroup="P 2 2 2", merge_friedel=True,
                      d_min=2.0, gain=1.0)
    on_disk = _train_and_merge(store, tmp_path / "a")
    in_memory = _train_and_merge(store.materialize(), tmp_path / "b")
    for key in ("F", "F_sd", "I0", "I0_sd", "edge_mass"):
        assert torch.equal(on_disk[key], in_memory[key]), key


def test_load_prep_builds_and_reuses_the_store(streams, tmp_path, parser, monkeypatch):
    from tests.test_cli_pipeline import _DataArgs
    monkeypatch.setattr(PS, "BLOCK_OBS", 50)
    cache = tmp_path / "prepared"
    args = _DataArgs(split=[f"a={streams[0]}", f"b={streams[1]}"], int_radius=None, gain=None,
                     cache_prep=cache, spacegroup="P 2 2 2")
    built = P.load_prep(args, verbose=False)
    assert isinstance(built.prep, PreparedStore)
    assert built.split_names == ["a", "b"]
    labels = built.prep.obs_info.delay_bin_idx
    assert labels.tolist() == sorted(labels.tolist()) and set(labels.tolist()) == {0, 1}

    def no_parse(*a, **k):
        raise AssertionError("a prepared-cache hit must not parse")
    monkeypatch.setattr(PS.StoreBuilder, "add", no_parse)
    again = P.load_prep(args, verbose=False)
    assert again.recipe == built.recipe and again.split_names == built.split_names
    assert torch.equal(again.prep.obs_info.delay_bin_idx, labels)
    args.gain = 2
    with pytest.raises(SystemExit, match="different settings"):
        P.load_prep(args, verbose=False)
    meta = json.loads((cache / "meta.json").read_text())
    meta["signature"]["observation_filter_version"] = -1
    (cache / "meta.json").write_text(json.dumps(meta))
    with pytest.raises(SystemExit, match="Rebuild it from the source"):
        P.load_prep(args, verbose=False)


def test_load_prep_reads_a_prepared_blob_of_an_earlier_run(streams, tmp_path, parser):
    """A run prepared before the store keeps its ``prepared.pt``; a merge reads it."""
    from tests.test_cli_pipeline import _DataArgs
    args = _DataArgs(stream=[streams[0]], int_radius=None, gain=None,
                     cache_prep=tmp_path / "prepared")
    built = P.load_prep(args, verbose=False)
    meta = json.loads((tmp_path / "prepared" / "meta.json").read_text())
    run = tmp_path / "run"
    run.mkdir()
    torch.save({"prep": built.prep.materialize(), "recipe": meta["recipe"],
                "split_names": meta["split_names"], "bg_var_factor": meta["bg_var_factor"],
                "signature": meta["signature"]}, run / "prepared.pt")
