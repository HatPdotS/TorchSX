"""Tests for write-back to .stream format."""

import torch

from torchsx.io._writeback import write_stream_reconstruct


def test_write_stream_reconstruct(sample_core, tmp_path):
    """Reconstruct a stream from tensors and check basic format."""
    out_path = tmp_path / "output.stream"
    write_stream_reconstruct(sample_core, out_path)

    text = out_path.read_text()

    assert "CrystFEL stream format 2.3" in text
    assert "Generated by torchsx" in text
    assert "Begin chunk" in text
    assert "End chunk" in text
    assert "Begin crystal" in text
    assert "End crystal" in text
    assert "Cell parameters" in text
    assert "Reflections measured after indexing" in text
    assert "End of reflections" in text


def test_write_stream_reflection_count(sample_core, tmp_path):
    """Output should contain the right number of reflection lines."""
    out_path = tmp_path / "output.stream"
    write_stream_reconstruct(sample_core, out_path)

    text = out_path.read_text()
    # Count lines between "Reflections measured" and "End of reflections"
    in_refl = False
    refl_count = 0
    for line in text.splitlines():
        if "Reflections measured after indexing" in line:
            in_refl = True
            continue
        if "End of reflections" in line:
            in_refl = False
            continue
        if in_refl and line.strip() and not line.strip().startswith("h"):
            refl_count += 1

    assert refl_count == 5  # total observations in sample_core


def test_write_stream_cell_nm(sample_core, tmp_path):
    """Cell in output should be in nm (not Å)."""
    out_path = tmp_path / "output.stream"
    write_stream_reconstruct(sample_core, out_path)

    text = out_path.read_text()
    for line in text.splitlines():
        if line.startswith("Cell parameters"):
            # Should be ~1.497 nm, not 14.97 Å
            parts = line.split()
            a_nm = float(parts[2])
            assert 1.0 < a_nm < 2.0, f"Cell a should be ~1.5 nm, got {a_nm}"
            break
