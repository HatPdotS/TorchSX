def test_raw_identity_and_spec_survive_transforms(stream_file, python_parser, tmp_path):
    from torchsx.io._parser import parse_stream

    parsed = parse_stream(stream_file, spacegroup="P 1")
    assert parsed.hkl.data_ptr() == parsed.observed_hkl.data_ptr()  # no ingestion copy
    raw = SFXStream.read(stream_file, spacegroup="P 1", merge_friedel=False)
    # P 1 has a trivial point group, so the signed ASU index is the observed one.
    assert torch.equal(raw.hkl, raw.observed_hkl)
    canonical = raw.symmetrize()
    assert torch.equal(canonical.observed_hkl, raw.hkl)
    assert torch.equal(canonical.I, raw.I) and torch.equal(canonical.sigma, raw.sigma)
    subset = canonical.filter_crystals(torch.tensor([False, True])).to("cpu")
    assert torch.equal(subset.observed_hkl, raw.hkl[3:])
    joined = SFXStream.concat([subset, subset])
    assert joined.measurement == raw.measurement
    assert joined.events == ["//8", "//8"]
    assert joined.metadata["image"]["source_file"] == [str(stream_file)] * 2
    assert joined._core.levels["crystal"]["source_lattice_index"].tolist() == [0, 0]
    for stream in (raw, canonical, joined):
        path = tmp_path / "roundtrip.sfx"
        stream.save(path)
        back = SFXStream.read(path, merge_friedel=stream.friedel_merged)
        assert back.measurement == stream.measurement == inspect_source(path)
        assert torch.equal(back.hkl, stream.hkl)
        assert torch.equal(back.observed_hkl, stream.observed_hkl)
        assert back.friedel_merged == stream.friedel_merged
        restored = SFXStream.load(path, merge_friedel=False)
        assert not restored.friedel_merged
        assert torch.equal(restored.hkl, stream.observed_hkl)


def test_parser_modes_are_equivalent(stream_file, python_parser):
    raw = SFXStream.read(stream_file, spacegroup="P 1", merge_friedel=False)
    for sequential in (True, False):
        sample = SFXStream.read(stream_file, spacegroup="P 1", merge_friedel=False,
                                max_crystals=raw.n_crystals, seed=13, sequential=sequential)
        assert raw.measurement == sample.measurement
        for name, level in raw._core.levels.items():
            for column in level:
                assert torch.equal(level[column], sample._core.levels[name][column]), (name, column)


def test_lattice_identity_is_not_renumbered(stream_file, python_parser):
    text = stream_file.read_text()
    start = text.index("--- Begin crystal")
    end = text.index("--- End crystal\n", start) + len("--- End crystal\n")
    text = text.replace("----- End chunk -----", text[start:end] + "\n----- End chunk -----")
    stream_file.write_text(text)
    raw = SFXStream.read(stream_file, spacegroup="P 1")
    assert raw.n_crystals == 4
    selected = raw.filter_crystals(torch.tensor([False, True, False, False]))
    assert selected._core.levels["crystal"]["source_lattice_index"].tolist() == [1]
    assert selected.filenames == ["/raw/a.h5"] and selected.events == ["//5"]


def test_concat_retains_each_sources_provenance(stream_file, python_parser, tmp_path):
    other_path = tmp_path / "other.stream"
    other_path.write_text(stream_file.read_text().replace("indexamajig ", "indexamajig -i another.lst "))
