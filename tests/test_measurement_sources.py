@pytest.mark.parametrize("options", ["--integration=rings-cen --int-radius=3,4,7",
                                     "--integration rings-cen --int-radius 3,4,7"])
@pytest.mark.parametrize("convention,value,expected", [("adu_per_photon", 1.0, 1.0),
                                                        ("adu_per_eV", 0.0003, 3.6)])
def test_header_semantics(tmp_path, options, convention, value, expected):
    path = tmp_path / "header.stream"
    path.write_text(f"CrystFEL stream format 2.3\nGenerated by CrystFEL 0.13.0\n"
                    f"indexamajig {options} -i 'literal;$(touch never)'\n"
                    f"----- Begin geometry file -----\n{convention} = {value} ; comment\n"
                    "; adu_per_photon = 666\n----- End geometry file -----\n"
                    "----- Begin chunk -----\nindexamajig --int-radius=1,2,3\n")
    spec = read_measurement(path)
    assert spec.producer_version == "0.13.0"
    assert spec.integration_modifiers == ("cen",)
    assert spec.radii == (3, 4, 7)
    assert (spec.nominal_n_peak, spec.nominal_n_bg) == _crystfel_pixel_counts(3, 4, 7)
    assert spec.pixel_count_definition == "nominal_integer_ring_mask"
    assert gain_from_measurement(spec, 12000) == pytest.approx(expected)
    assert not (tmp_path / "never").exists()
    assert MeasurementSpec.from_dict(spec.to_dict()) == spec
    with pytest.raises(FrozenInstanceError):
        spec.radii = (1, 2, 3)


def test_missing_zero_and_unknown_semantics(stream_file):
    spec = read_measurement(stream_file)
    missing = replace(spec, gain_declarations=())
    assert resolve_measurement(missing).gain == "auto"
    with pytest.raises(ValueError, match="gain unavailable"):
        resolve_measurement(missing, gain="trust_input")
    zero = replace(spec, gain_declarations=(("global", "adu_per_photon", 0),))
    with pytest.raises(ValueError, match="Invalid"):
        gain_from_measurement(zero, 12000)
    assert resolve_measurement(zero, gain=1).gain == 1
    for change in ({"integration_method": "prof2d"}, {"background_definition": "summed_background"},
                   {"uncertainty_definition": "variance"}, {"upstream_corrections": ("lp",)}):
        with pytest.raises(ValueError, match="Unsupported measurement semantics"):
            resolve_measurement(replace(spec, **change), radii="3,4,7", gain=1)
    unknown = replace(spec, unresolved=("integration_modifiers",))
    with pytest.raises(ValueError, match="confirm"):
        resolve_measurement(unknown)
    assert resolve_measurement(unknown, radii="3,4,7").radii == spec.radii


