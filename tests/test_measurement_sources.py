def test_recipe_precedence(stream_file):
    spec = read_measurement(stream_file)
    unknown_checkpoint = {"radii": None, "gain": None, "measurement": None}
    assert resolve_measurement(spec, defaults=unknown_checkpoint).radii == spec.radii
    checkpoint = {"radii": [2, 3, 6], "gain": "auto",
                  "measurement": {"gain_adu_per_photon": 43.0}}
