def test_auto_metadata_matches_explicit_prep_and_posterior(stream_file, python_parser, tmp_path):
    from torchsx.merging.parameters import Parameters
    from tests.test_cli_pipeline import _stack
    auto = P.load_prep(_args(stream_file), verbose=False)
    explicit_args = _args(stream_file)
    explicit_args.int_radius, explicit_args.gain = "3,4,7", 1.0
    explicit = P.load_prep(explicit_args, verbose=False)
    assert auto.recipe["measurement"]["gain_adu_per_photon"] == 1.0
    for field in fields(auto.prep):
        left, right = getattr(auto.prep, field.name), getattr(explicit.prep, field.name)
        if isinstance(left, torch.Tensor):
            assert torch.equal(left, right), field.name
    results = []
    for bundle in (auto, explicit):
        torch.manual_seed(7)
        params = Parameters.from_prep(bundle.prep)
        scale, _, trainer = _stack(bundle.prep, params, tmp_path)
        scale.eval()
        results.append(trainer.merge())
    for key in ("F", "F_sd", "I0", "I0_sd", "edge_mass"):
        assert torch.allclose(results[0][key], results[1][key], rtol=1e-5, atol=1e-6), key


def test_preparation_accepts_semantics_from_a_future_adapter(stream_file, python_parser):
    raw = SFXStream.read(stream_file, spacegroup="P 1")
    expected = prepare_observations(raw, MergeConfig())
    metadata = StreamMetadata(raw.metadata)
    spec = replace(raw.measurement, producer="future_fixture", intensity_unit="photon",
                   background_unit="photon/pixel", gain_declarations=())
    metadata[MEASUREMENT_KEY] = {"record": spec.to_dict()}
    future = SFXStream(raw._core.replace(metadata=metadata))
    got = prepare_observations(future, MergeConfig())
    assert torch.equal(got.I_obs, expected.I_obs) and torch.equal(got.bg, expected.bg)
    metadata[MEASUREMENT_KEY] = {"record": replace(spec, intensity_definition="profile_fit").to_dict()}
    with pytest.raises(ValueError, match="Unsupported measurement semantics"):
        prepare_observations(SFXStream(raw._core.replace(metadata=metadata)), MergeConfig())


@pytest.mark.parametrize("mode", ["auto", "empirical"])
def test_requested_gain_calibration_still_runs(stream_file, python_parser, monkeypatch, mode):
    calls = []
    def calibrate(self, *args):
        calls.append(mode)
        return (3.0, 0.0, 0.0) if mode == "auto" else 3.0
    method = "calibrate_sigma2_of_bg" if mode == "auto" else "calibrate_gain"
    monkeypatch.setattr(PoissonNoiseModel, method, calibrate)
    args = _args(stream_file)
    args.gain = mode
    calibrated = P.load_prep(args, verbose=False)
    args.gain = 3.0
    explicit = P.load_prep(args, verbose=False)
    assert calls == [mode]
    assert calibrated.recipe["measurement"]["gain_adu_per_photon"] == 3.0
    assert torch.equal(calibrated.prep.I_obs, explicit.prep.I_obs)
    assert torch.equal(calibrated.prep.bg, explicit.prep.bg)
    assert torch.equal(calibrated.prep.obs_info.sigma, explicit.prep.obs_info.sigma)


def test_prepared_cache_recipe_and_legacy_compatibility(stream_file, python_parser, tmp_path, monkeypatch):
    cache, sfx = tmp_path / "prep.pt", tmp_path / "parsed.sfx"
    args = _args(stream_file, cache_prep=cache, sfx_cache=sfx)
    built = P.load_prep(args, verbose=False)
    def no_parse(*a, **k):
        raise AssertionError("prepared-cache hit must not parse tensors")
    monkeypatch.setattr(SFXStream, "read", no_parse)
    again = P.load_prep(args, verbose=False)
    assert again.recipe == built.recipe
    # merge_nn can reuse training's cache with the checkpoint's numeric gain.
    assert P.load_prep(args, recipe_defaults=built.recipe, verbose=False).recipe == built.recipe
    args.gain = 2
    with pytest.raises(SystemExit, match="different settings"):
        P.load_prep(args, verbose=False)
    args.stream = [tmp_path / "missing.stream"]
    args.trust_cache_prep = True
    assert P.load_prep(args, verbose=False).recipe == built.recipe
    # Simulate a pre-contract cache, retaining the old signature/explicit recipe.
    blob = torch.load(cache, weights_only=False)
    for key in ("measurement", "source_files"):
        blob["signature"].pop(key)
    blob["recipe"].pop("measurement")
    blob["signature"]["gain"] = 1.0
    torch.save(blob, cache)
    args.stream, args.trust_cache_prep = [stream_file], False
    args.int_radius, args.gain = "3,4,7", 1.0
    assert P.load_prep(args, verbose=False).prep.n_valid == built.prep.n_valid


def test_legacy_sfx_requires_recipe_and_refuses_to_invent_hkl_state(sample_core, tmp_path):
    path = tmp_path / "legacy.sfx"
    SFXStream(sample_core.replace(friedel_merged=False)).save(path)
    assert inspect_source(path) is None
    args = _args(path)
    with pytest.raises(SystemExit, match="radii unavailable"):
        P.load_prep(args, verbose=False)
    args.int_radius, args.gain = "3,4,7", 1.0
    bundle = P.load_prep(args, verbose=False)
    assert bundle.recipe["measurement"]["source"] is None
    sidecar_path = path.with_suffix(".sfx.json")
    sidecar = json.loads(sidecar_path.read_text())
    sidecar.pop("friedel_merged")
    sidecar_path.write_text(json.dumps(sidecar))
    # A sidecar predating the flag reads as already merged and kept no observed
    # index, so asking to keep the mates apart must fail rather than quietly put
    # them all on one side.
    with pytest.raises(ValueError, match="Cannot separate Friedel mates"):
        SFXStream.load(path, merge_friedel=False)
    assert SFXStream.load(path).friedel_merged


@pytest.mark.parametrize("trust", [False, True])
@pytest.mark.parametrize("version", [None, -1])
def test_prepared_cache_requires_current_observation_filter(stream_file, python_parser, tmp_path, trust, version):
    cache = tmp_path / "prep.pt"
    args = _args(stream_file, cache_prep=cache)
    P.load_prep(args, verbose=False)
    blob = torch.load(cache, weights_only=False)
    if version is None:
        blob["signature"].pop("observation_filter_version")
    else:
        blob["signature"]["observation_filter_version"] = version
    torch.save(blob, cache)
    args.trust_cache_prep = trust
    with pytest.raises(SystemExit, match="Rebuild it from the source"):
        P.load_prep(args, verbose=False)
